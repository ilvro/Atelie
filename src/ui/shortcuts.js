/**
 * Agrupa os atalhos por categoria.
 * @returns {Record<string, typeof SHORTCUTS>}
 */
export function getShortcutsByCategory() {
  const groups = {};
  for (const s of SHORTCUTS) {
    if (!groups[s.category]) groups[s.category] = [];
    groups[s.category].push(s);
  }
  return groups;
}

